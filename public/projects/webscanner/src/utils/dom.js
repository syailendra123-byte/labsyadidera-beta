  /* ---- Toast ---- */
  let toastTimer = null;
  function toast(message, type) {
    const host = document.getElementById('toast-host');
    if (!host) return;
    host.innerHTML = '';
    const t = h('div', { class: 'toast' + (type === 'error' ? ' toast-error' : ''), role: type === 'error' ? 'alert' : 'status' },
      type === 'error' ? icon('alert', 18) : null, h('span', null, message));
    host.appendChild(t);
    clearTimeout(toastTimer);
    toastTimer = setTimeout(() => { t.classList.add('toast-out'); setTimeout(() => t.remove(), 220); }, type === 'error' ? 5200 : 3200);
  }

  /* ---- Konfirmasi ---- */
  function confirmDialog(message, okLabel) {
    return new Promise((resolve) => {
      const host = document.getElementById('dialog-host');
      const done = (v) => { host.innerHTML = ''; resolve(v); };
      const box = h('div', { class: 'dialog', role: 'alertdialog', 'aria-modal': 'true' },
        h('p', { class: 'dialog-text' }, message),
        h('div', { class: 'dialog-actions' },
          h('button', { class: 'btn btn-quiet', onclick: () => done(false) }, 'Batal'),
          h('button', { class: 'btn btn-danger', onclick: () => done(true) }, okLabel || 'Hapus')));
      host.innerHTML = '';
      host.appendChild(h('div', { class: 'backdrop backdrop-center', onclick: (e) => { if (e.target === e.currentTarget) done(false); } }, box));
      box.querySelector('.btn-danger').focus();
    });
  }

